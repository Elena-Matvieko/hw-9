// Напишите программу, которая на протяжении 30 секунд каждые 3 секунды будет выводить в консоль текущую дату.
//  Последней строкой должно выводиться сообщение «30 секунд прошло».

// Устанавливаем интервал: выводить дату каждые 3000 миллисекунд (3 секунды)
const intervalId = setInterval(() => {
    console.log(new Date().toLocaleString());
}, 3000);

// Устанавливаем таймер: через 30000 миллисекунд (30 секунд) остановить процесс
const timeoutId = setTimeout(() => {
    // Обязательно очищаем интервал, чтобы он не продолжал работать в фоне
    clearInterval(intervalId);
    
    // Выводим финальное сообщение
    console.log('30 секунд прошло');
}, 30000);